const MAX_ATTEMPTS: usize = 20;

fn pick_hero() -> &'static str {
    HERO_NAMES[random_index(HERO_NAMES.len())]
}

fn random_index(max: usize) -> usize {
    let max = max as u64;
    let limit = (1_u64 << 32) - ((1_u64 << 32) % max);
    loop {
        let mut bytes = [0_u8; 4];
        getrandom::fill(&mut bytes).expect("operating system randomness is unavailable");
        let value = u32::from_le_bytes(bytes) as u64;
        if value < limit {
            return (value % max) as usize;
        }
    }
}

fn assemble_slug() -> String {
    format!("{}-{}-{}", pick_hero(), pick_hero(), pick_hero())
}

pub fn generate_hero_slug(id: &str, existing: &HashSet<String>) -> String {
    let mut slug = String::new();
    let mut collided = true;
    for _ in 0..MAX_ATTEMPTS {
        slug = assemble_slug();
        if !existing.contains(&slug) {
            collided = false;
            break;
        }
    }
    if collided {
        let prefix = id.encode_utf16().take(8).collect::<Vec<_>>();
        slug = format!("{slug}-{}", String::from_utf16_lossy(&prefix));
    }
    slug
}
